"""Deterministic Programmatic Verifier (Phase 2).
Replaces expensive and fallible LLM judges with $0 billed, deterministic ground-truth verification:
1. Numeric verifier (regex extraction, float comparison with tolerance)
2. Code verifier (AST safety inspection + sandboxed subprocess unit test executor)
3. Exact-match QA verifier (normalization, multiple-choice letter extraction, alias matching)
"""

import ast
import re
import string
import subprocess
import sys
import tempfile
from pathlib import Path


# ─────────────────────────────────────────────────────────────────────────────
# 1. Numeric Verifier (Math, GSM8K, Parametric Probes)
# ─────────────────────────────────────────────────────────────────────────────

def strip_thought_tags(text: str) -> str:
    """Remove thought tags generated by reasoning models."""
    cleaned = re.sub(r"<thought>.*?</thought>", "", text, flags=re.DOTALL).strip()
    return cleaned if cleaned else text


def _clean_numeric_str(s: str) -> str:
    """Remove currency symbols, commas, and trailing punctuation."""
    return s.replace("$", "").replace(",", "").strip().rstrip(".")


def extract_numbers_from_text(text: str) -> list[float]:
    """Extract candidate numbers from text, prioritizing common answer formats."""
    text = strip_thought_tags(text)
    prioritized: list[float] = []

    # Pattern 1: Look for GSM8K delimiter "#### <num>"
    gsm_match = re.search(r"####\s*[\$*_`]*([+-]?(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?)", text)
    if gsm_match:
        try:
            prioritized.append(float(_clean_numeric_str(gsm_match.group(1))))
        except ValueError:
            pass

    # Pattern 2: Look for explicit answer statements (e.g., "answer is $42", "answer: 42", "= $42")
    ans_patterns = [
        r"(?:answer is|answer:|=|is equal to)\s*[\$*_`]*([+-]?(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?)",
        r"\*\*[\$*_`]*([+-]?(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?)\*\*",  # bolded number
    ]
    for pat in ans_patterns:
        matches = re.findall(pat, text, re.IGNORECASE)
        if matches:
            try:
                prioritized.append(float(_clean_numeric_str(matches[-1])))
            except ValueError:
                pass

    # Pattern 3: Extract all float/integer tokens (including comma-separated numbers like 1,250.00)
    raw_tokens = re.findall(r"[-+]?(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?", text)
    valid_nums = []
    for tok in raw_tokens:
        clean = _clean_numeric_str(tok)
        try:
            val = float(clean)
            valid_nums.append(val)
        except ValueError:
            continue

    # Order candidates: prioritized first, then the very last number from text, then all valid numbers
    candidates = []
    seen = set()
    for num in prioritized + (valid_nums[-1:] if valid_nums else []) + valid_nums:
        if num not in seen:
            seen.add(num)
            candidates.append(num)

    return candidates


def verify_numeric(
    response: str,
    expected_answer: str | float | int,
    tolerance: float = 0.01,
) -> bool:
    """Verify numeric response against expected numerical ground truth."""
    if not response or response.strip() == "":
        return False

    try:
        expected_val = float(_clean_numeric_str(str(expected_answer)))
    except ValueError:
        return False

    candidates = extract_numbers_from_text(response)
    if not candidates:
        return False

    # Check candidates (check the last number first, then any candidate)
    ordered_candidates = [candidates[-1]] + candidates[:-1]
    for cand in ordered_candidates:
        diff = abs(cand - expected_val)
        if diff <= tolerance:
            return True

    return False


# ─────────────────────────────────────────────────────────────────────────────
# 2. Code Verifier (MBPP, Python Functions, Unit Tests)
# ─────────────────────────────────────────────────────────────────────────────

# Obvious unsafe AST nodes / modules blocked before execution
DISALLOWED_MODULES = {"os", "sys", "subprocess", "socket", "pty", "shutil", "requests", "httpx"}


def extract_code_block(text: str) -> str:
    """Extract python code block from markdown or return raw text."""
    text = strip_thought_tags(text)
    # Look for ```python ... ```
    match = re.search(r"```(?:python)?\s*\n(.*?)```", text, re.DOTALL | re.IGNORECASE)
    if match:
        return match.group(1).strip()

    # Look for generic ``` ... ```
    match = re.search(r"```\s*\n(.*?)```", text, re.DOTALL)
    if match:
        return match.group(1).strip()

    # Fallback to lines that look like Python definitions
    lines = text.split("\n")
    code_lines = []
    in_code = False
    for line in lines:
        if line.strip().startswith(("def ", "import ", "from ", "class ")) or in_code:
            in_code = True
            code_lines.append(line)
    if code_lines:
        return "\n".join(code_lines).strip()

    return text.strip()


def is_ast_safe(code_str: str) -> bool:
    """Check AST for forbidden imports or system operations."""
    try:
        tree = ast.parse(code_str)
    except SyntaxError:
        return False

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split(".")[0] in DISALLOWED_MODULES:
                    return False
        elif isinstance(node, ast.ImportFrom):
            if node.module and node.module.split(".")[0] in DISALLOWED_MODULES:
                return False
        elif isinstance(node, ast.Call):
            # Block built-in dangerous functions like eval(), exec(), __import__()
            if isinstance(node.func, ast.Name) and node.func.id in ("eval", "exec", "__import__", "open"):
                return False

    return True


def verify_code(
    response: str,
    test_list: list[str],
    setup_code: str = "",
    timeout_sec: float = 4.0,
) -> bool:
    """Execute code response against test assertions in an isolated subprocess."""
    code = extract_code_block(response)
    if not code:
        return False

    if not is_ast_safe(code):
        return False

    # Assemble test script
    test_body = "\n".join(test_list)
    full_script = f"{setup_code}\n\n{code}\n\n# Tests\n{test_body}\n"

    with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False) as f:
        f.write(full_script)
        temp_path = Path(f.name)

    try:
        res = subprocess.run(
            [sys.executable, str(temp_path)],
            timeout=timeout_sec,
            capture_output=True,
            text=True,
        )
        return res.returncode == 0
    except (subprocess.TimeoutExpired, Exception):
        return False
    finally:
        if temp_path.exists():
            try:
                temp_path.unlink()
            except OSError:
                pass


# ─────────────────────────────────────────────────────────────────────────────
# 3. Exact-Match QA Verifier (ARC, TriviaQA, Multiple Choice)
# ─────────────────────────────────────────────────────────────────────────────

def _normalize_text(s: str) -> str:
    """Lowercase, strip punctuation and extra whitespace."""
    s = s.lower().strip()
    s = "".join(ch for ch in s if ch not in string.punctuation or ch in ("-",))
    return " ".join(s.split())


def extract_mcq_letter(response: str) -> str | None:
    """Extract single-letter MCQ choice from LLM response (e.g. 'A', '(B)', 'Answer: C')."""
    # Pattern 1: Explicit answer statements
    patterns = [
        r"(?:the correct answer is|the answer is|answer:)\s*\(?([A-D])\)?\b",
        r"\b(?:option|choice)\s*\(?([A-D])\)?\b",
        r"^\s*\(?([A-D])\)?[\.\:\s]*$",  # standalone letter
        r"\*\*\(?([A-D])\)?\*\*",         # bolded letter
    ]
    for pat in patterns:
        m = re.search(pat, response, re.IGNORECASE | re.MULTILINE)
        if m:
            return m.group(1).upper()

    # Pattern 2: First standalone letter A-D in the first line or last line
    lines = [l.strip() for l in response.strip().split("\n") if l.strip()]
    for line in [lines[-1], lines[0]]:
        m = re.search(r"\b([A-D])\b", line)
        if m:
            return m.group(1).upper()

    return None


def verify_exact_match(
    response: str,
    expected_answer: str,
    aliases: list[str] | None = None,
) -> bool:
    """Verify QA response against expected text/letter and acceptable aliases."""
    if not response or not response.strip():
        return False

    response = strip_thought_tags(response)
    clean_resp = _normalize_text(response)
    expected_str = str(expected_answer).strip()

    # Check for multiple-choice single letter match (e.g. 'A', 'B', 'C', 'D')
    if len(expected_str) == 1 and expected_str.upper() in "ABCD":
        extracted_letter = extract_mcq_letter(response)
        if extracted_letter == expected_str.upper():
            return True

    # Check normalized match against expected and all aliases
    targets = [expected_str] + (aliases or [])
    for target in targets:
        clean_target = _normalize_text(target)
        if not clean_target:
            continue

        # Exact substring or word boundary match
        if clean_target in clean_resp:
            return True
        pattern = r"\b" + re.escape(clean_target) + r"\b"
        if re.search(pattern, clean_resp):
            return True

    return False


# ─────────────────────────────────────────────────────────────────────────────
# Master Dispatch Verifier
# ─────────────────────────────────────────────────────────────────────────────

def verify(response: str, item_spec: dict) -> bool:
    """Dispatch verification according to item's answer_type."""
    spec = item_spec.get("answer_spec", item_spec)
    answer_type = spec.get("answer_type", "")

    if answer_type == "numeric":
        expected = spec.get("answer")
        tol = float(spec.get("tolerance", 0.01))
        return verify_numeric(response, expected, tolerance=tol)

    if answer_type == "code_test":
        test_list = spec.get("test_list", [])
        setup_code = spec.get("test_setup_code", "")
        return verify_code(response, test_list, setup_code=setup_code)

    if answer_type == "exact_match":
        expected = spec.get("answer", "")
        aliases = spec.get("answer_aliases", [])
        return verify_exact_match(response, expected, aliases=aliases)

    # Unknown or non-verifiable type
    return False
